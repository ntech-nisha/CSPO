# CUSTOMER RFM + PRODUCT LEVEL BILLING SYSTEM (INDIA) - STREAMLIT FULL PROGRAM WITH VISUALIZATION
# ====================================================================================================

import streamlit as st
import pandas as pd
from datetime import datetime
from sklearn.cluster import KMeans
import plotly.express as px

st.set_page_config(page_title="Customer Billing + RFM Clustering Dashboard", layout="wide")
st.title("🛍 Customer RFM Dashboard + Product Billing (India)")

# ----------------------------------------------------------------------------------------------------
# COLUMN MAPPING (auto map different Excel column names)
# ----------------------------------------------------------------------------------------------------
COLUMN_MAPPING = {
    "Customer ID": "CustomerID",
    "Customer Id": "CustomerID",
    "customer id": "CustomerID",
    "Price": "Amount",
    "UnitPrice": "Amount",
    "Unit Price": "Amount",
    "Description": "Product",
    "Invoice Date": "InvoiceDate",
    "Invoice_No": "Invoice",
    "InvoiceNo": "Invoice",
}

# ----------------------------------------------------------------------------------------------------
# FILE UPLOAD
# ----------------------------------------------------------------------------------------------------
uploaded = st.file_uploader("📂 Upload Excel file", type=["xlsx", "xls"])

if uploaded:
    df = pd.read_excel(uploaded)

    # Auto rename columns if they exist
    df.rename(columns=COLUMN_MAPPING, inplace=True)

    required_cols = {"CustomerID", "Amount", "InvoiceDate", "Product"}

    if not required_cols.issubset(df.columns):
        st.error(f"❌ Excel file does not contain required columns\nRequired → {required_cols}\nFound → {set(df.columns)}")
        st.stop()

    df["InvoiceDate"] = pd.to_datetime(df["InvoiceDate"], errors="coerce")
    df.dropna(subset=["InvoiceDate"], inplace=True)

    st.success("✅ File uploaded. Columns auto-mapped successfully.")

    # ✅ DATA PREVIEW
    st.write("### 👀 Data Preview")
    st.dataframe(df.head())

    # ------------------------------------------------------------------------------------------------
    #  ✅ R F M   C A L C U L A T I O N
    # ------------------------------------------------------------------------------------------------
    st.subheader("📊 RFM Segmentation")

    max_date = df["InvoiceDate"].max()

    rfm = df.groupby("CustomerID").agg({
        "InvoiceDate": lambda x: (max_date - x.max()).days,   # Recency
        "Invoice": "count",                                   # Frequency
        "Amount": "sum"                                       # Monetary
    }).reset_index()

    rfm.columns = ["CustomerID", "Recency", "Frequency", "Monetary"]

    # Fix NaN / Infinite issues before clustering
    rfm.fillna(0, inplace=True)
    rfm = rfm.replace([float('inf'), -float('inf')], 0)

    # KMeans
    kmeans = KMeans(n_clusters=3, random_state=0)
    rfm["Cluster"] = kmeans.fit_predict(rfm[["Recency", "Frequency", "Monetary"]])

    # ------------------------------------------------------------------------------------------------
    #  ✅ R F M   V I S U A L I Z A T I O N (Bar + Scatter)
    # ------------------------------------------------------------------------------------------------

    # Bar Graph – Monetary by Cluster
    st.write("### 📈 Bar Graph: Total Monetary Value by Cluster")
    bar = rfm.groupby("Cluster")["Monetary"].sum().reset_index()
    fig = px.bar(bar, x="Cluster", y="Monetary")
    st.plotly_chart(fig, use_container_width=True)

    # Scatter – Frequency vs Monetary
    st.write("### 📌 Scatter Plot: Frequency vs Monetary")
    fig2 = px.scatter(rfm, x="Frequency", y="Monetary", color="Cluster", hover_data=["CustomerID"])
    st.plotly_chart(fig2, use_container_width=True)

    st.success("✅ RFM clustering & visualization completed.")

    # ------------------------------------------------------------------------------------------------
    #  ✅ PRODUCT LEVEL DISCOUNT (EDITABLE)
    # ------------------------------------------------------------------------------------------------
    st.subheader("🏷 Product Based Discount (Editable for Each Product Row)")

    unique_products = df["Product"].unique()
    discount_df = pd.DataFrame({
        "Product": unique_products,
        "Discount(₹)": [0] * len(unique_products)  # default rupee-based discount
    })

    updated_discount_df = st.data_editor(discount_df, num_rows="dynamic")

    # Merge entered discount into billing dataframe
    df = df.merge(updated_discount_df, on="Product", how="left")

    df["FinalAmount"] = df["Amount"] - df["Discount(₹)"]
    df["FinalAmount"] = df["FinalAmount"].apply(lambda x: max(x, 0))  # avoid negative billing

    st.write("### 🧾 Final Billing (After Discount)")
    st.dataframe(df[["CustomerID", "Product", "Amount", "Discount(₹)", "FinalAmount"]])

    st.subheader(f"💰 Final Bill Total: ₹{df['FinalAmount'].sum()}")

else:
    st.info("📌 Please upload Excel file to continue.")
