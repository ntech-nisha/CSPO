# =========================================
# CUSTOMER RFM + BILLING (INDIA STREAMLIT)
# FREQUENCY BASED DISCOUNT + BILLING ENTRY
# =========================================

import streamlit as st
import pandas as pd
import numpy as np
from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
import plotly.express as px

st.set_page_config(page_title="Customer RFM + Indian Billing Dashboard", layout="wide")
st.title("🛍️ Customer RFM + Indian Billing Dashboard")

# -----------------------------------
# Helper: auto detect column names
# -----------------------------------
def find_col(df, candidates):
    for c in candidates:
        if c in df.columns:
            return c
    lower_cols = {col.lower(): col for col in df.columns}
    for c in candidates:
        if c.lower() in lower_cols:
            return lower_cols[c.lower()]
    return None


# -----------------------------------
# SIDEBAR SETTINGS
# -----------------------------------
st.sidebar.header("⚙️ Discount Settings (Frequency Based)")
big_discount = st.sidebar.number_input("BIG Discount % (Frequency ≥ 5)", min_value=0, max_value=100, value=20)
medium_discount = st.sidebar.number_input("MEDIUM Discount % (Frequency ≥ 3)", min_value=0, max_value=100, value=10)
small_discount = st.sidebar.number_input("SMALL Discount % (Frequency ≥ 2)", min_value=0, max_value=100, value=5)

n_clusters = st.sidebar.slider("KMeans Clusters (K)", min_value=2, max_value=8, value=4)


# --------------------------------------------------------------
# SESSION STATE FOR BILLING (Important fix)
# --------------------------------------------------------------
if "invoice_items" not in st.session_state:
    st.session_state.invoice_items = []


# -----------------------------------
# 1) FILE UPLOAD
# -----------------------------------
st.header("1️⃣ Upload sales/transactions file (CSV or Excel)")
uploaded_file = st.file_uploader("Upload CSV / XLSX file", type=["csv", "xlsx"])

if uploaded_file:
    if uploaded_file.name.endswith(".csv"):
        df = pd.read_csv(uploaded_file, dtype=str)
    else:
        df = pd.read_excel(uploaded_file, dtype=str)

    df.columns = [c.strip() for c in df.columns]

    product_col = find_col(df, ["Product", "Description", "Item", "Product Name"])
    customer_col = find_col(df, ["Customer ID", "CustomerID", "customer_id"])
    price_col = find_col(df, ["Price", "UnitPrice", "Rate", "Amount"])
    qty_col = find_col(df, ["Quantity", "Qty", "Units"])
    invoice_date_col = find_col(df, ["InvoiceDate", "Date", "TransactionDate"])

    if not product_col or not customer_col or not price_col:
        st.error("❌ Required columns missing: Customer ID, Product, Price")
        st.stop()

    df["Product"] = df[product_col].astype(str)
    df["CustomerID"] = df[customer_col].astype(str).str.strip()
    df["Price"] = pd.to_numeric(df[price_col], errors="coerce").fillna(0)

    if qty_col:
        df["Quantity"] = pd.to_numeric(df[qty_col], errors="coerce").fillna(1).astype(int)
    else:
        df["Quantity"] = 1

    if invoice_date_col:
        df["InvoiceDate"] = pd.to_datetime(df[invoice_date_col], errors="coerce")
    else:
        df["InvoiceDate"] = pd.NaT

    df["TotalAmount"] = df["Price"] * df["Quantity"]

    st.success("✅ File loaded and mapped")
    st.dataframe(df.head())


    # -----------------------------------
    # 2) RFM CALCULATION & CLUSTERING
    # -----------------------------------
    st.header("2️⃣ RFM Segmentation + Cluster Visualization")

    snapshot_date = df["InvoiceDate"].max() + pd.Timedelta(days=1)

    rfm = df.groupby("CustomerID").agg(
        Recency=("InvoiceDate", lambda x: (snapshot_date - x.max()).days),
        Frequency=("Product", "count"),
        Monetary=("TotalAmount", "sum")
    ).reset_index()

    # ✅ FIX NaN / infinite for clustering
    rfm = rfm.dropna(subset=["Recency", "Frequency", "Monetary"])
    rfm = rfm.replace([np.inf, -np.inf], 0)

    rfm_clust = rfm.copy()
    rfm_clust[["R_log", "F_log", "M_log"]] = np.log1p(rfm_clust[["Recency", "Frequency", "Monetary"]])

    X = StandardScaler().fit_transform(rfm_clust[["R_log", "F_log", "M_log"]])
    rfm["Cluster"] = KMeans(n_clusters=n_clusters, random_state=42, n_init=10).fit_predict(X)

    # 3D Visual
    fig3d = px.scatter_3d(
        rfm, x="Recency", y="Frequency", z="Monetary",
        color="Cluster", hover_data=["CustomerID"], title="3D Cluster View (RFM Clusters)"
    )
    st.plotly_chart(fig3d, use_container_width=True)


    # --- Bar Graphs ---
    col1, col2, col3 = st.columns(3)
    col1.plotly_chart(px.bar(rfm.groupby("Cluster")["Recency"].mean(), title="Avg Recency"))
    col2.plotly_chart(px.bar(rfm.groupby("Cluster")["Frequency"].mean(), title="Avg Frequency"))
    col3.plotly_chart(px.bar(rfm.groupby("Cluster")["Monetary"].mean(), title="Avg Monetary"))


    # -----------------------------------
    # 3) BILLING SECTION (Single Customer)
    # -----------------------------------
    st.header("3️⃣ Billing — Single Customer Invoice")

    cust_id = st.text_input("Enter Customer ID (Exact Match)")

    if cust_id:
        product_name = st.text_input("Enter Product Name")
        price = st.number_input("Enter Unit Price (₹)", min_value=0, value=0)
        freq = st.number_input("Enter Frequency", min_value=1, value=1, step=1)

        if st.button("➕ Add to Invoice"):
            if freq >= 5:
                offer = f"BIG Discount ({big_discount}%)"
                discount_amount = int(price * freq * big_discount / 100)
            elif freq >= 3:
                offer = f"MEDIUM Discount ({medium_discount}%)"
                discount_amount = int(price * freq * medium_discount / 100)
            elif freq >= 2:
                offer = f"SMALL Discount ({small_discount}%)"
                discount_amount = int(price * freq * small_discount / 100)
            else:
                offer = "NO Discount"
                discount_amount = 0

            final = (price * freq) - discount_amount

            # ✅ FIX: Store inside session_state
            st.session_state.invoice_items.append(
                [product_name, freq, offer, price, discount_amount, final]
            )

        if st.session_state.invoice_items:
            invoice_df = pd.DataFrame(
                st.session_state.invoice_items,
                columns=["Product", "Frequency", "Offer Type", "Unit Price (₹)", "Discount (₹)", "Final Price (₹)"]
            )
            st.table(invoice_df)

            if st.button("💰 Calculate FINAL TOTAL"):
                st.success(f"✅ Grand Total (₹): {invoice_df['Final Price (₹)'].sum()}")

else:
    st.info("⬆️ Upload a sales file to continue.")
